import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
import {createRegionalView,unpackReference} from '../web/regional.js';
import {packReference} from '../supabase/functions/navigation-sync/sync.mjs';

test('全量区域可筛选、下钻和导出，未划入地市的区县不丢失',async()=>{
  const html=await readFile(new URL('../web/index.html',import.meta.url),'utf8');
  const data=JSON.parse(await readFile(new URL('../private/reference-latest.json',import.meta.url),'utf8'));
  const dom=new JSDOM(html,{url:'https://example.com'}),w=dom.window;
  const $=id=>w.document.getElementById(id);
  const reference={data,scope:'原站全品目数据，含作业监测设备',generated:data.meta.generated,checkedAt:new Date().toISOString()};
  const packed=await packReference(reference);
  assert.ok(JSON.stringify(packed).length<JSON.stringify(reference).length/2);
  assert.deepEqual((await unpackReference(packed)).data,data);
  const options=new Map();
  w.echarts={getMap:()=>({}),init:el=>({setOption:option=>options.set(el.id,option),off(){},on(){},resize(){},clear(){}})};
  let exported;w.Blob=Blob;w.URL.createObjectURL=blob=>{exported=blob;return 'blob:test';};w.URL.revokeObjectURL=()=>{};
  w.HTMLAnchorElement.prototype.click=function(){};
  const view=createRegionalView({document:w.document,request:async()=>[{payload:packed}],number:v=>Number(v||0).toLocaleString('zh-CN')});
  await view.open();
  assert.equal($('regional-rows').children.length,26);
  assert.equal($('regional-quantity').textContent,data.statsYear['全国'].all[1].toLocaleString('zh-CN'));
  assert.match($('regional-status').textContent,/2136个区县/);
  assert.equal(options.get('regional-map').series[0].data.length,26);
  $('regional-province').value='北京市';$('regional-province').onchange();
  $('regional-city').value='未划入地市';$('regional-city').onchange();
  assert.ok([...$('regional-county').options].some(option=>option.value==='首农'));
  $('regional-city').value='';$('regional-city').onchange();
  $('regional-county').value='延庆区';$('regional-county').onchange();
  assert.equal($('regional-quantity').textContent,data.countyStat['北京市']['延庆区'].all[1].toLocaleString('zh-CN'));
  assert.equal($('regional-detail-panel').hidden,false);
  $('regional-year').value='2026';$('regional-year').onchange();
  assert.equal($('regional-quantity').textContent,data.countyStat['北京市']['延庆区']['2026'][1].toLocaleString('zh-CN'));
  assert.ok([...$('regional-month-rows').rows].every(row=>row.cells[0].textContent.startsWith('2026-')));
  $('regional-month-export').onclick();assert.match(await exported.text(),/原站全品目/);
  $('regional-source-export').onclick();assert.deepEqual(JSON.parse(await exported.text()).data,data);
  view.clear();assert.equal($('regional-rows').children.length,0);dom.window.close();
});
